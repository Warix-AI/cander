export function uiPrimitiveFile(name: string): ScaffoldFile | null {
  const content = PRIMITIVES[name];
  if (!content) return null;
  return { path: `components/ui/${name}.tsx`, content };
}

export function resolveUiPrimitiveFiles(names: string[]): {
  files: ScaffoldFile[];
  missing: string[];
} {
  const files: ScaffoldFile[] = [];
  const missing: string[] = [];
  const seen = new Set<string>();
  for (const raw of names) {
    const name = raw.replace(/\.tsx$/, "").replace(/^components\/ui\//, "");
    if (seen.has(name)) continue;
    seen.add(name);
    const file = uiPrimitiveFile(name);
    if (!file) missing.push(name);
    else files.push(file);
  }
  return { files, missing };
}

