/**
 * Inject per-app Supabase env into a build sandbox (never commit secrets).
 * Server-only.
 */

import { ensureAppSupabaseProject } from "@/lib/build/supabase/provision";
import { getComputerProvider } from "@/lib/computer/providers/vercel-sandbox-computer-provider";
import { runPrivilegedSandboxCommand } from "@/lib/build/sandbox/privileged";
import { commitFilesToDraftBranch } from "@/lib/build/git/commit-draft";

export type InjectSupabaseResult = {
  ok: boolean;
  status: string;
  projectRef: string | null;
  message?: string;
};

/**
 * Ensure app Supabase + write sandbox `.env.local` (gitignored).
 * Commits only a secret-free `.env.example` to the draft branch.
 */
export async function injectAppSupabaseIntoSandbox(opts: {
  userId: string;
  projectId: string;
  workspaceId: string;
  sessionId: string;
}): Promise<InjectSupabaseResult> {
  const ensured = await ensureAppSupabaseProject({
    projectId: opts.projectId,
    workspaceId: opts.workspaceId,
    includeSecrets: true,
  });

  // User-defined + vault-backed env vars for the development scope join the
  // Supabase connection vars. Same source of truth as the Vercel sync.
  let extraEnv: Array<{ name: string; value: string }> = [];
  try {
    const { resolveEnvForScope } = await import("@/lib/build/env/sync");
    extraEnv = (await resolveEnvForScope({ projectId: opts.projectId, scope: "development" })).filter(
      (e) => !["NEXT_PUBLIC_SUPABASE_URL", "NEXT_PUBLIC_SUPABASE_ANON_KEY", "SUPABASE_SERVICE_ROLE_KEY"].includes(e.name),
    );
  } catch (err) {
    console.warn("[cander] env vars for sandbox skipped", err instanceof Error ? err.message : err);
  }
  if (ensured.status === "skipped") {
    // Static websites still get their own settings (form/API keys) in the sandbox.
    if (extraEnv.length) {
      await getComputerProvider().writeFile(
        opts.sessionId,
        opts.userId,
        ".env.local",
        [`# Generated by Cander — do not commit`, ...extraEnv.map((e) => `${e.name}=${quoteEnv(e.value)}`), ""].join("\n"),
      );
    }
    return {
      ok: true,
      status: "skipped",
      projectRef: null,
      message: ensured.message,
    };
  }

  if (ensured.status !== "ready" || !ensured.url || !ensured.secrets?.anonKey) {
    return {
      ok: false,
      status: ensured.status,
      projectRef: ensured.projectRef,
      message: ensured.message || "Supabase not ready for env inject.",
    };
  }

  const provider = getComputerProvider();
  const envLocal = [
    `# Generated by Cander — do not commit`,
    `NEXT_PUBLIC_SUPABASE_URL=${ensured.url}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${ensured.secrets.anonKey}`,
    ensured.secrets.serviceRoleKey
      ? `SUPABASE_SERVICE_ROLE_KEY=${ensured.secrets.serviceRoleKey}`
      : `# SUPABASE_SERVICE_ROLE_KEY=`,
    ...extraEnv.map((e) => `${e.name}=${quoteEnv(e.value)}`),
    "",
  ].join("\n");

  const envExample = [
    `# Copy to .env.local — Cander injects real values in the sandbox`,
    `NEXT_PUBLIC_SUPABASE_URL=`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=`,
    `# Server-only — never expose to the browser`,
    `# SUPABASE_SERVICE_ROLE_KEY=`,
    ...extraEnv.map((e) => `${e.name}=`),
    "",
  ].join("\n");

  await provider.writeFile(
    opts.sessionId,
    opts.userId,
    ".env.local",
    envLocal,
  );
  await provider.writeFile(
    opts.sessionId,
    opts.userId,
    ".env.example",
    envExample,
  );

  // Ensure secrets stay out of git
  try {
    await runPrivilegedSandboxCommand({
      sessionId: opts.sessionId,
      userId: opts.userId,
      cmd: "sh",
      args: [
        "-c",
        `touch .gitignore; grep -qxF '.env.local' .gitignore || echo '.env.local' >> .gitignore; grep -qxF '.env*.local' .gitignore || echo '.env*.local' >> .gitignore`,
      ],
    });
  } catch {
    /* optional */
  }

  // Persist secret-free example + gitignore to draft (not .env.local)
  try {
    let gitignore = "";
    try {
      gitignore = await provider.readFile(
        opts.sessionId,
        opts.userId,
        ".gitignore",
      );
    } catch {
      gitignore = "";
    }
    if (!gitignore.includes(".env.local")) {
      gitignore = `${gitignore.trimEnd()}\n.env.local\n.env*.local\n`;
    }
    await commitFilesToDraftBranch({
      projectId: opts.projectId,
      workspaceId: opts.workspaceId,
      message: "Cander: add Supabase env example",
      files: [
        { path: ".env.example", content: envExample },
        { path: ".gitignore", content: gitignore },
      ],
    });
  } catch (err) {
    console.warn("[cander] supabase env example commit skipped", err);
  }

  return {
    ok: true,
    status: "ready",
    projectRef: ensured.projectRef,
    message: "Supabase env injected into sandbox.",
  };
}

function quoteEnv(value: string): string {
  return /[\s#"'$]/.test(value) ? JSON.stringify(value) : value;
}
